### 5.4 Why the threshold grows with thickness

The obvious candidate is the **aspect ratio** of the A,B domain: it is a flat
disc of thickness \$h\$ (the slab) and in-plane diameter \$D\$, and like a liquid
sheet it might be expected to break up once it is wide enough relative to its
thickness. Taking the largest \$D/h\$ each run reached while its A,B domain was
still one piece:

ASPECT_TABLE

**The full scan does not support a universal \$D/h\$ threshold.** The two groups
overlap heavily: runs that stayed as one blob reached ratios well above ones
that broke up. Sorting by \$D/h\$ interleaves the outcomes rather than separating
them.

An earlier version of this write-up claimed \$D/h\\gtrsim5\$ "separates every
run". That was based on seven exploratory runs and is **wrong** — with the full
20-point map the claim does not survive.

What the data does show is that the critical ratio depends systematically on
thickness, and in the *opposite* direction to the naive picture — thicker slabs
fragment at a **lower** aspect ratio:

CRITICAL_ASPECT_TABLE

So a thin domain has to be proportionally much wider than a thick one before it
will break up. That is consistent with the monolayer being quasi-2D: rearranging
cells to pinch a domain in two requires neighbour exchanges that a single layer
cannot make out-of-plane, so break-up is kinetically suppressed there and the
domain simply stretches instead.

The geometric relation is still worth writing down. Since the domain packs
\$n_{AB}\$ cells into \$h/2r\$ layers,

\$\$
D \\;=\\; 4\\sqrt{\\frac{n_{AB}\\,2r}{\\pi h}}
\\qquad\\Longrightarrow\\qquad
n_{AB} \\;=\\; \\frac{\\pi}{16}\\Bigl(\\frac{D}{h}\\Bigr)^{2}\\frac{h^{3}}{2r},
\$\$

so at *fixed* aspect ratio the cell count would grow like \$h^{3}\$. The measured
\$N_0\$ thresholds grow more slowly than that — see §5.3 — precisely because the
critical ratio falls with thickness, which partly cancels the \$h^{3}\$.

**Bottom line.** The model reproduces the experimental rule *thicker aggregates
need more cells to pattern* (§5.3), but the mechanism is not a single geometric
threshold. Geometry sets the scale; the kinetic competition between coarsening
and the one-way \$A\\to B\\to C\$ conversion sets where the line actually falls.

## 6. Caveats

* The adhesion scale is a **kinetic window**, not a free multiplier. At
  `layers = 1`, \$N_0=500\$: \$\\times0.70\$ gives loose porous patches,
  \$\\times1.00\$ compact stable islands, \$\\times1.40\$ a single blob. The set sits
  at \$\\times1.00\$ and is not far from either edge.
* BC fusion is qualitatively right but quantitatively more fused than the
  reference (§5.1). This is the one trade-off that could not be removed: the same
  softening that makes the islands work costs BC fidelity.
* `layers = 1` needs `rep_wall = 150` with \$\\Delta t=0.0075\$; a wall stiff enough
  to hold the sheet flat is unstable at \$\\Delta t=0.015\$. `wall_settings(layers)`
  selects this automatically.
* **One seed per phase-map point, and verdicts near a threshold are not robust.**
  This is not a generic disclaimer — it was observed directly. `layers = 1`,
  \$N_0=200\$ classified as `ISLANDS` at \$\\Delta t=0.0075\$ and as `transient` at
  \$\\Delta t=0.005\$, with everything else identical. The table brackets each
  threshold; it does not resolve it to better than roughly a factor of two, and
  the island *counts* at a boundary point should not be quoted as exact
  (the same run gave 3 islands at one timestep and 4 at another). Repeat over
  seeds before drawing a line on a figure.
* The islands are transient by construction: \$f_{AB}\\to0\$, so run long enough and
  every pattern eventually dissolves into a pure C sea. The comparison window is
  \$t\\approx200\\text{–}650\$ (1 hour \$=15\$ model time units).

