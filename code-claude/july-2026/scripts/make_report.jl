"(largest N0 without islands, smallest N0 with islands, islands at that N0)"
function bracket(L)
    sub = filter(r -> r.layers == L, rows)
    yes = sort(filter(r -> r.verdict == "ISLANDS", sub); by = r -> r.N0)
    no  = filter(r -> r.verdict != "ISLANDS", sub)
    if isempty(yes)
        nmax = isempty(no) ? nothing : maximum(r.N0 for r in no)
        return (nmax, nothing, 0)
    end
    first_yes = yes[1]
    below = filter(r -> r.N0 < first_yes.N0, no)
    nmax  = isempty(below) ? nothing : maximum(r.N0 for r in below)
    (nmax, first_yes.N0, first_yes.n_isl)
end

