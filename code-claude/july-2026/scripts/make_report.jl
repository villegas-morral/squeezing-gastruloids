## 1. What this had to do

One set of mechanical parameters had to reproduce three separate observations:

1. **Fusion.** Two aggregates of pure cell type, placed in contact, must fuse the
   way the experiment says they do — and in particular the **B–C** pair must
   *glue* rather than round up into a single sphere.
2. **Polarisation** (unconfined). A spherical aggregate with an A,B core inside a
   C shell must polarise: A,B segregating to one pole.
3. **Patterns** (confined). Squeezed between plates of thickness `layers`, the
   A,B mass must break into **islands in a C sea**, above a critical initial
   cell number \$N_0\$ that grows with thickness.

## 2. The model

Cells are spheres of radius \$r\$ with a pairwise force, attractive between
contact and a cutoff \$\\mu r_{ij}\$:

\$\$
F_{ij}(d) \\;=\\; f_{s_i s_j}\\,\\Bigl(\\frac{r_{ij}}{d}-1\\Bigr)\\Bigl(\\mu_{s_i s_j}\\frac{r_{ij}}{d}-1\\Bigr),
\\qquad r_{ij}=2r,
\$\$

with \$f=f_\\mathrm{rep}\$ for \$d<r_{ij}\$ and \$f=f_\\mathrm{att}\$ above. Motion is
overdamped, with the drag shared over the \$n_i\$ contacting neighbours and a
neighbour-velocity alignment term \$\\alpha_\\mathrm{ecm}\$:

\$\$
\\mathbf v_i \\;=\\; \\frac{1}{\\lambda n_i}\\Bigl(\\mathbf F_i + \\alpha_\\mathrm{ecm}\\!\\!\\sum_{j\\in\\mathcal N(i)}\\!\\!\\mathbf v_j\\Bigr).
\$\$

Differentiation is one-way, \$A\\to B\\to C\$, with rates suppressed by the global
A fraction \$f_A\$:

\$\$
r_{AB}=\\frac{p}{1+k f_A},\\qquad r_{BC}=\\frac{q}{1+k f_A}.
\$\$

\$p\$ and \$q\$ are **fixed** at the experimental values (\$p\\simeq 10q\$) and were
never tuned here.

## 3. The parameter set

The final set is the collaborator's *fusion* set with **exactly two diagonal
entries of \$f_\\mathrm{rep}\$ softened**:

```julia
mu    = 2 * [1    0.91 1    ;  f_att = 4 * [0.9 1.0 0.6 ;   f_rep = 3 * [3 1 1   ;
             0.91 1    1    ;               1.0 1.6 0.4 ;                1 1 1   ;
             1    1    1.07]                0.6 0.4 0.75]                1 1 1.7]
```

| | changed? |
|---|---|
| \$\\mu\$ | no — collaborator's matrix |
| \$f_\\mathrm{att}\$ | no — collaborator's matrix |
| \$f_\\mathrm{rep}\$ off-diagonals, **[2,3] included** | no |
| \$f_\\mathrm{rep}[2,2]\$ | \$6\\to3\$ |
| \$f_\\mathrm{rep}[3,3]\$ | \$6\\to5.1\$ |
| \$p,q\$ | no |

**Why the softening is necessary.** With the stiff \$f_\\mathrm{rep}\$ the A,B phase
never coarsens: at `layers = 1`, \$N_0=500\$ it stays a salt-and-pepper dispersion
(clustered fraction 0.31, largest cluster 12 cells) and simply differentiates
away. Softening the B–B and C–C self-repulsion lets it round up into compact
islands (clustered 0.86, islands of 23, 22, 21, 16, 14 cells).

**Why \$f_\\mathrm{att}\$ is *not* rescaled.** An earlier version of this work used
\$f_\\mathrm{att}\\times0.45\$. That was tuned against a broken confinement (§4) and
is wrong: at \$\\times0.45\$ the C–C and A–C pairs stop fusing altogether and the
monolayer islands dissolve. Note also that a uniform \$f_\\mathrm{att}\$ scale is
**not** harmless — it preserves the *ratios* of surface and interfacial tensions,
hence contact angles, but \$f_\\mathrm{rep}\$ is not scaled with it, so the
tension-to-elasticity ratio moves, and that is what decides whether an aggregate
can round up at all.

## 4. Two bugs that had been driving the conclusions

**(a) The plates did not confine.** The wall force was a *constant*,
`fz += rep_wall` while \$z<r\$. A constant force has no stable fixed point inside
the contact zone: it pushes the cell until \$z\\ge r\$ and then switches off. At
`layers = 1` the band available to cell centres is only \$L-2r = 0.1\$, while one
restoring step displaces \$\\;\\texttt{rep\\_wall}\\,\\Delta t/(\\lambda n_i)\\approx0.075\$,
so cells chattered straight across it.

| layers | cells outside the plates (old wall) | effective thickness |
|---|---|---|
| 1 | **93 %** | 1.95 cells |
| 2 | 2 % | 2.02 |
| 3 | 0.3 % | 3.00 |
| 4 | 0.2 % | 4.00 |

Every earlier `layers = 1` result therefore described a buckled bilayer, not a
monolayer. The fix is a Hookean plate,

\$\$ F_z = \\texttt{rep\\_wall}\\,\\frac{r-z}{r}, \$\$

which vanishes at contact — so the contact point *is* the fixed point — and
cannot be outrun by in-plane crowding. Stability requires
\$\\texttt{rep\\_wall}\\cdot\\Delta t<2\$ (the \$n_i<2\$ branch of the equations of
motion drops the \$1/n_i\$ drag), giving `rep_wall = 60` at \$\\Delta t=0.015\$ and
`150` at \$\\Delta t=0.0075\$; larger values send the positions to `NaN`.

**(b) The readout was ~300 time units too late.** Since \$A\\to B\\to C\$ is one-way,
the A,B phase is a *transient* and \$f_{AB}\\to0\$. Scoring each run at the first
frame with \$f_{AB}\\le0.12\$ lands after the islands have both formed and begun to
erode. Runs are now scored over the whole trajectory (`island_timeline`), and a
run only counts as patterned if islands are present at the **end**; one that
fragments and then dissolves is reported as `transient`.

## 5. Results

### 5.1 Fusion

Two aggregates of 150 cells each, no division, no differentiation; the metric is
COM separation over \$R_{g,1}+R_{g,2}\$ (\$\\approx1.6\$ at contact, \$\\approx0.5\$ once
rounded into one sphere). Lower means more fused.

| pair | reference | this set | |
|---|---|---|---|
| AA | 1.614 | 1.702 | never fuses ✓ |
| BB | 0.537 | 0.531 | rounds up ✓ |
| CC | 0.562 | 0.536 | rounds up ✓ |
| **BC** | **0.947** | **0.744** | **glues, does not round** ✓ |
| AB | 0.470 | 0.138 | fuses |
| AC | 0.657 | 0.510 | fuses |

BC is the least-fused pair by a wide margin — every pair that does fuse sits at
\$\\le0.536\$. This is predictable analytically: with
\$W_{ij}=f_\\mathrm{att}[i,j]\\,2r\\,A(\\mu_{ij})\$ where
\$A(\\mu)=(1+\\mu)\\ln\\mu-2(\\mu-1)\$, the interfacial tensions
\$\\gamma_{ij}=\\tfrac12(W_{ii}+W_{jj})-W_{ij}\$ come out

\$\$ \\gamma_{AB}=0.405,\\quad \\gamma_{AC}=0.232,\\quad \\gamma_{BC}=0.581, \$\$

so BC has the largest interfacial cost and every pair is in Steinberg's *partial
engulfment* class (a stable doublet with a finite contact angle).

**Caveat.** BC at 0.744 is more rounded than the reference 0.947. Softening
\$f_\\mathrm{rep}[2,2]\$ and \$[3,3]\$ makes the B and C aggregates softer, so the
doublet rounds a little further before it stops. The ordering is right; the
number is not a match.

