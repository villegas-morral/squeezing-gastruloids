# ---- aspect-ratio table, computed from the saved trajectories -----------------
# The largest D/h each run reached while its A,B domain was still one piece.
# Computed here rather than hardcoded so the number cannot drift from the data.
function peak_aspect(file, L)
    d = load_frames(file)
    best = 0.0
    for k in 5:length(d.x)
        x, y, z, s = d.x[k], d.y[k], d.z[k], d.cell_state[k]
        cls = classify_islands(island_stats(x, y, z, s, L))
        a = ab_domain_aspect(x, y, z, s)
        cls == "single" || cls == "dispersed" || break
        isnan(a.ratio) || (best = max(best, a.ratio))
    end
    best
end

